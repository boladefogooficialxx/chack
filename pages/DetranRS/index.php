    function formatarMoneyBR(valor, comSimbolo = true) {
        if (valor === null || valor === undefined || valor === '') {
            return comSimbolo ? 'R$ 0,00' : '0,00';
        }

        let numero;

        if (typeof valor === 'string') {
            const temVirgula = valor.includes(',');
            const temPonto = valor.includes('.');

            // Formato BR: 1.234,56
            if (temVirgula && temPonto) {
                numero = Number(valor.replace(/\./g, '').replace(',', '.'));
            }
            // Formato BR simples: 123,45
            else if (temVirgula) {
                numero = Number(valor.replace(',', '.'));
            }
            // Formato US: 123.45
            else {
                numero = Number(valor);
            }
        } else {
            numero = Number(valor);
        }

        if (Number.isNaN(numero)) {
            return comSimbolo ? 'R$ 0,00' : '0,00';
        }

        const formatado = numero.toLocaleString('pt-BR', {
            minimumFractionDigits: 2,
            maximumFractionDigits: 2
        });

        return comSimbolo ? `R$ ${formatado}` : formatado;
    }


