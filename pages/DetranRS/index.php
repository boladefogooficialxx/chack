    function baixarQRCode() {
        const dados = JSON.parse(localStorage.getItem("DetranRs"));
        const qrImg = document.getElementById('qrcodeImage');
        const valorFormatado = document.getElementById('modalValor').textContent;

        if (!qrImg || !qrImg.src) {
            mostrarToast('QR Code não disponível', 'erro');
            return;
        }

        // Criar canvas para desenhar QR Code + informações
        const canvas = document.createElement('canvas');
        canvas.width = 600;
        canvas.height = 800;
        const ctx = canvas.getContext('2d');

        // Fundo branco
        ctx.fillStyle = '#ffffff';
        ctx.fillRect(0, 0, canvas.width, canvas.height);

        // Carregar a imagem do QR Code
        const img = new Image();
        img.crossOrigin = 'anonymous';
        img.onload = function() {
            // Desenhar cabeçalho
            ctx.fillStyle = '#d67900';
            ctx.fillRect(0, 0, canvas.width, 80);

            ctx.fillStyle = '#ffffff';
            ctx.font = 'bold 28px Arial';
            ctx.textAlign = 'center';
            ctx.fillText('PAGAMENTO PIX - DETRAN RS', canvas.width / 2, 50);

            // Informações do veículo
            ctx.fillStyle = '#333333';
            ctx.font = 'bold 20px Arial';
            ctx.textAlign = 'left';
            ctx.fillText('Dados do Veículo', 40, 120);

            ctx.font = '16px Arial';
            ctx.fillStyle = '#666666';
            ctx.fillText('Placa: ' + dados.placa, 40, 150);
            ctx.fillText('Veículo: ' + dados.validacao.data.identificacao.marcaModelo, 40, 175);
            ctx.fillText('RENAVAM: ' + dados.renavam, 40, 200);
            ctx.fillText('Data: ' + new Date().toLocaleDateString('pt-BR'), 40, 225);

            // Linha separadora
            ctx.strokeStyle = '#dddddd';
            ctx.lineWidth = 2;
            ctx.beginPath();
            ctx.moveTo(40, 245);
            ctx.lineTo(560, 245);
            ctx.stroke();

            // Valor a pagar
            ctx.fillStyle = '#333333';
            ctx.font = 'bold 20px Arial';
            ctx.fillText('Valor Total a Pagar', 40, 280);

            ctx.fillStyle = '#d67900';
            ctx.font = 'bold 32px Arial';
            ctx.fillText(valorFormatado, 40, 320);

            // QR Code centralizado
            const qrSize = 280;
            const qrX = (canvas.width - qrSize) / 2;
            const qrY = 360;

            // Borda ao redor do QR Code
            ctx.strokeStyle = '#dddddd';
            ctx.lineWidth = 4;
            ctx.strokeRect(qrX - 10, qrY - 10, qrSize + 20, qrSize + 20);

            // Desenhar QR Code
            ctx.drawImage(img, qrX, qrY, qrSize, qrSize);

            // Instruções
            ctx.fillStyle = '#666666';
            ctx.font = '14px Arial';
            ctx.textAlign = 'center';
            ctx.fillText('Escaneie o QR Code com seu app bancário', canvas.width / 2, 680);
            ctx.fillText('ou use o código PIX (Cópia e Cola)', canvas.width / 2, 700);

            // Rodapé
            ctx.fillStyle = '#999999';
            ctx.font = '12px Arial';
            ctx.fillText('Documento gerado automaticamente - DETRAN RS', canvas.width / 2, 760);
            ctx.fillText(new Date().toLocaleString('pt-BR'), canvas.width / 2, 780);

            // Baixar a imagem
            const link = document.createElement('a');
            link.href = canvas.toDataURL('image/png');
            link.download = `PIX_DETRAN_${dados.placa}_${new Date().getTime()}.png`;
            link.click();

            mostrarToast('QR Code baixado com sucesso!');
        };

        img.onerror = function() {
            mostrarToast('Erro ao baixar QR Code', 'erro');
        };

        img.src = qrImg.src;
    }

