        document.getElementById('pixCode').value = pixCode;

        // Mostrar modal e loading
        document.getElementById('modalPix').style.display = 'flex';
        document.getElementById('qrcodeLoading').style.display = 'block';
        document.getElementById('qrcodeImage').style.display = 'none';

        // Gerar QR Code via API (mais confiável)
        const qrImg = document.getElementById('qrcodeImage');
        const loading = document.getElementById('qrcodeLoading');

        // Usar API de QR Code
        const encodedPixCode = encodeURIComponent(pixCode);
        const qrUrl = `https://api.qrserver.com/v1/create-qr-code/?size=280x280&data=${encodedPixCode}`;

        // Esperar a imagem carregar para mostrar
